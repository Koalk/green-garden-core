// Regenerates packages/web-ui/src/pilot-data.ts from catalogue-draft/*.json.
// The bundled sample (PILOT) stays at the 10 pilot plants; SPECIES lists all of them for the species search.
// Run: node scripts/gen-pilot-fixture.mjs   (a web-ui test fails if the two drift apart)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { linksOfEntry } from "../packages/catalogue/src/links.ts";
import { root } from "./lib.mjs";

const dir = `${root}/catalogue-draft`;
const PILOT_IDS = [
  "aloe-vera",
  "chlorophytum-comosum",
  "crassula-ovata",
  "dracaena-trifasciata",
  "epipremnum-aureum",
  "ficus-elastica",
  "monstera-deliciosa",
  "pilea-peperomioides",
  "spathiphyllum-wallisii",
  "zamioculcas-zamiifolia",
];

/** The first photo of an entry, only the fields the app shows. */
const photoOf = (p) => ({
  file: p.file,
  creator: p.creator,
  licence: p.licence,
  licenceUrl: p.licenceUrl,
  sourceUrl: p.sourceUrl,
  thumbnail: p.thumbnail,
});

/** outdoor care facts, only the ones the entry has; "not researched" (null) stays out. */
function outdoorOf(c) {
  const o = {};
  const pick = (key, v) => {
    if (v !== undefined && v !== null) o[key] = v;
  };
  pick("rootDepth", c.rootDepthClass?.value);
  pick("droughtTolerance", c.droughtTolerance?.value);
  pick("dormancy", c.dormancy?.value);
  pick("establishmentSeasons", c.establishment?.seasons?.value);
  pick("establishingIntervalDays", c.establishment?.intervalDays?.value);
  return Object.keys(o).length === 0 ? {} : { outdoor: o };
}

const all = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => {
    const e = JSON.parse(readFileSync(`${dir}/${f}`, "utf8")).entries[0];
    const c = e.care;
    const doc = JSON.parse(readFileSync(`${dir}/${f}`, "utf8"));
    const src = doc.sources.find(
      (x) => x.id === (c.wateringStyle.source ?? c.baseIntervalDays.source),
    );
    const links = linksOfEntry(e, doc.sources);
    return {
      id: e.id,
      name: e.names.common[0].name,
      scientificName: e.taxon.scientificName,
      style: c.wateringStyle.value,
      intervalDays: c.baseIntervalDays.value,
      restFactor: c.restSeasonFactor.value,
      dryTolDays: c.dryToleranceDays.value,
      wetTolDays: c.wetToleranceDays.value,
      confidence: `style ${c.wateringStyle.confidence}, interval ${c.baseIntervalDays.confidence}, tolerances ${c.dryToleranceDays.confidence}`,
      careSource:
        src === undefined ? "author knowledge, to be verified" : `${src.publisher ?? src.title}`,
      commonNames: e.names.common.map((n) => n.name),
      ...(e.names.common.some((n) => n.lang !== "en-GB")
        ? {
            localNames: e.names.common
              .filter((n) => n.lang !== "en-GB")
              .map((n) => ({ lang: n.lang, name: n.name })),
          }
        : {}),
      synonyms: e.names.synonyms,
      tags: e.tags?.curated ?? [],
      habit: c.habit?.value ?? null,
      toxicity: {
        status: e.toxicity.status,
        exposures: e.toxicity.exposures.map((x) => ({ who: x.who, severity: x.severity })),
      },
      ...outdoorOf(c),
      ...(e.lookAlikes === undefined ? {} : { lookAlikes: e.lookAlikes }),
      ...(e.lookAlikeNote === undefined ? {} : { lookAlikeNote: e.lookAlikeNote }),
      ...(e.nameIdeas === undefined ? {} : { nameIdeas: e.nameIdeas }),
      ...(e.photoFile === undefined ? {} : { photoFile: e.photoFile }),
      ...(e.photos?.[0] === undefined ? {} : { photo: photoOf(e.photos[0]) }),
      ...(links.length === 0 ? {} : { links }),
    };
  });

// The sample plants need every field; an unknown style falls back to let_top_dry and says so.
const pilot = all
  .filter((r) => PILOT_IDS.includes(r.id))
  .map((r) => ({
    id: r.id,
    name: r.name,
    scientificName: r.scientificName,
    intervalDays: r.intervalDays,
    restFactor: r.restFactor,
    dryTolDays: r.dryTolDays,
    wetTolDays: r.wetTolDays,
    style: r.style ?? "let_top_dry",
    confidence:
      r.style === null
        ? `style unknown (default let_top_dry), ${r.confidence.split(", ").slice(1).join(", ")}`
        : r.confidence,
  }));

const text = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by scripts/gen-pilot-fixture.mjs from catalogue-draft/*.json. Do not edit by hand.

import type { LearnLink } from "@green-garden/catalogue";

export interface PilotRow {
  readonly id: string;
  readonly name: string;
  readonly scientificName: string;
  readonly style: "keep_moist" | "let_top_dry" | "let_fully_dry";
  readonly intervalDays: number;
  readonly restFactor: number;
  readonly dryTolDays: number;
  readonly wetTolDays: number;
  readonly confidence: string;
}

export interface SpeciesRow {
  readonly id: string;
  readonly name: string;
  readonly scientificName: string;
  readonly style: PilotRow["style"] | null;
  readonly intervalDays: number | null;
  readonly restFactor: number | null;
  readonly dryTolDays: number | null;
  readonly wetTolDays: number | null;
  readonly confidence: string;
  /** Publisher of the watering-style source, or a note that it is author knowledge. */
  readonly careSource: string;
  readonly commonNames: readonly string[];
  /** Common names in languages other than English (UK), for the name matcher. */
  readonly localNames?: readonly { readonly lang: string; readonly name: string }[];
  readonly synonyms: readonly string[];
  readonly tags: readonly string[];
  readonly habit: string | null;
  readonly toxicity: {
    readonly status: "assessed" | "unknown";
    readonly exposures: readonly { readonly who: string; readonly severity: number }[];
  };
  /** Absent = not researched yet, which is different from "none". */
  readonly lookAlikes?: readonly {
    readonly name: string;
    readonly species?: string;
    readonly tell: string;
  }[];
  /** outdoor care facts the entry has; absent when it has none. */
  readonly outdoor?: {
    readonly rootDepth?: "shallow" | "medium" | "deep";
    readonly droughtTolerance?: "none" | "moderate" | "high";
    readonly dormancy?: "none" | "winter" | "summer";
    readonly establishmentSeasons?: 1 | 2 | 3;
    readonly establishingIntervalDays?: number;
  };
  readonly lookAlikeNote?: string;
  readonly nameIdeas?: readonly string[];
  /** Wikimedia Commons file name. */
  readonly photoFile?: string;
  /** Bundled thumbnail (catalogue package, thumbs/) with the credit its licence needs. */
  readonly photo?: {
    readonly file: string;
    readonly creator: string;
    readonly licence: string;
    readonly licenceUrl: string;
    readonly sourceUrl: string;
    readonly thumbnail: string;
  };
  /** "Learn more" pages, in every language the entry has; learnMoreLinks picks by UI language. */
  readonly links?: readonly LearnLink[];
}

/** The bundled demo sample: the 10 pilot plants. */
export const PILOT: readonly PilotRow[] = ${JSON.stringify(pilot, null, 2)};

/** Every catalogue species, for the species search. Unknown values are null. */
export const SPECIES: readonly SpeciesRow[] = ${JSON.stringify(all, null, 2)};
`;
writeFileSync(`${root}/packages/web-ui/src/pilot-data.ts`, text);
console.log(`wrote ${pilot.length} sample rows, ${all.length} species`);
