// `pnpm i18n:check` verifies the locale files; `pnpm i18n:new <tag> "<Language name>"` starts a new one.
// Both keep packages/i18n/src/catalogues.ts (the import list the browser needs) in step.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { checkCatalogues, newLocaleFile, usedKeysIn } from "../packages/i18n/src/check.ts";
import { fail, root, walk } from "./lib.mjs";

const dir = `${root}/packages/i18n/src/locales`;
const catalogueFile = `${root}/packages/i18n/src/catalogues.ts`;
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const tags = () =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".json") && f !== "meta.json")
    .map((f) => f.slice(0, -5))
    .sort((a, b) => (a === "en-GB" ? -1 : b === "en-GB" ? 1 : a.localeCompare(b)));

function catalogueSource() {
  const names = tags().map((t) => [t, `l_${t.replace(/[^A-Za-z0-9]/g, "_")}`]);
  return [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "// Generated by scripts/i18n.mjs from the files in ./locales. Do not edit by hand.",
    "",
    ...names.map(([t, v]) => `import ${v} from "./locales/${t}.json" with { type: "json" };`),
    "",
    `export const CATALOGUES: Readonly<Record<string, Readonly<Record<string, string>>>> = {`,
    ...names.map(([t, v]) => `  ${/^[A-Za-z_]\w*$/.test(t) ? t : JSON.stringify(t)}: ${v},`),
    "};",
    "",
  ].join("\n");
}

function sourceUsage() {
  const literals = new Set();
  const prefixes = new Set();
  const asked = new Set();
  for (const f of walk()) {
    if (!/^packages\/[^/]+\/src\/.*\.ts$/.test(f) || f.startsWith("packages/i18n/")) continue;
    const u = usedKeysIn(readFileSync(`${root}/${f}`, "utf8"));
    u.literals.forEach((k) => literals.add(k));
    u.prefixes.forEach((k) => prefixes.add(k));
    u.asked.forEach((k) => asked.add(k));
  }
  return { literals, prefixes, asked };
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "check") {
  const catalogues = Object.fromEntries(tags().map((t) => [t, readJson(`${dir}/${t}.json`)]));
  const { errors, warnings } = checkCatalogues({
    catalogues,
    meta: readJson(`${dir}/meta.json`),
    usage: sourceUsage(),
  });
  if (!existsSync(catalogueFile) || readFileSync(catalogueFile, "utf8") !== catalogueSource()) {
    errors.push("packages/i18n/src/catalogues.ts is out of date: run `pnpm i18n:new --sync`");
  }
  warnings.forEach((w) => console.warn(`warning: ${w}`));
  if (errors.length) fail("Locale problems:", errors);
  console.log(`i18n: ok (${Object.keys(catalogues).length} locales, ${warnings.length} warnings)`);
} else if (cmd === "new") {
  if (args[0] === "--sync") {
    writeFileSync(catalogueFile, catalogueSource());
    console.log("catalogues.ts regenerated");
  } else {
    const [tag, name] = args;
    if (!/^[a-z]{2,3}(-[A-Z]{2})?$/.test(tag ?? "") || !name) {
      console.error(
        'usage: pnpm i18n:new <tag, e.g. de or pt-BR> "<language name in that language>"',
      );
      process.exit(2);
    }
    if (existsSync(`${dir}/${tag}.json`)) fail("Locale exists:", [tag]);
    const meta = readJson(`${dir}/meta.json`);
    meta[tag] = { name, machine: true };
    writeFileSync(
      `${dir}/${tag}.json`,
      JSON.stringify(newLocaleFile(readJson(`${dir}/en-GB.json`)), null, 2) + "\n",
    );
    writeFileSync(`${dir}/meta.json`, JSON.stringify(meta, null, 2) + "\n");
    writeFileSync(catalogueFile, catalogueSource());
    console.log(
      `Created locales/${tag}.json with the English text. Translate the values, keep the keys and {placeholders}.`,
    );
  }
} else {
  console.error("usage: node scripts/i18n.mjs check | new <tag> <name> | new --sync");
  process.exit(2);
}
